#!/usr/bin/env node
/**
 * Bundles the module's scripts (public/js/**\/*.js) into one versioned file,
 * public/dist/userinterface.js, plus public/dist/manifest.json.
 *
 * The scripts are classic (non-module) scripts sharing globals, so the bundle is
 * an ordered concatenation, in exactly the order the layout loads them one by one
 * (Support\Assets::jsAssets(): relative path, byte order). Behaviour is the same;
 * the browser makes 1 request instead of ~37.
 *
 * Usage:  npm run build           write the bundle
 *         npm run build:check     exit 1 if the committed bundle is out of date (CI)
 */
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jsDir = join(root, 'public', 'js');
const distDir = join(root, 'public', 'dist');
const bundlePath = join(distDir, 'userinterface.js');
const manifestPath = join(distDir, 'manifest.json');
const checkOnly = process.argv.includes('--check');

async function listJs(dir) {
    const entries = await readdir(dir, { withFileTypes: true });
    const files = [];
    for (const entry of entries) {
        const full = join(dir, entry.name);
        if (entry.isDirectory()) {
            files.push(...await listJs(full));
        } else if (entry.name.endsWith('.js')) {
            files.push(full);
        }
    }
    return files;
}

// Same order as Assets::jsAssets(): forward-slash relative path, plain byte comparison.
const sources = (await listJs(jsDir))
    .map((full) => ({ full, path: relative(jsDir, full).split(sep).join('/') }))
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));

let bundle = '/*! iquesters/user-interface — generated by `npm run build`, do not edit. Sources: public/js/ */\n';
for (const { full, path } of sources) {
    // LF only: the bundle must be byte-identical on Windows and Linux checkouts (CI check).
    const code = (await readFile(full, 'utf8')).replace(/^﻿/, '').replace(/\r\n?/g, '\n');
    // Leading ';' guards against a previous file that ends without one.
    bundle += `\n;/* ---- js/${path} ---- */\n${code.trimEnd()}\n`;
}

const hash = createHash('sha256').update(bundle).digest('hex').slice(0, 12);
const manifest = JSON.stringify({ file: 'dist/userinterface.js', hash, sources: sources.map((s) => `js/${s.path}`) }, null, 4) + '\n';

if (checkOnly) {
    const current = await readFile(bundlePath, 'utf8').catch(() => '');
    if (current !== bundle) {
        console.error('public/dist/userinterface.js is out of date: run `npm run build` and commit the result.');
        process.exit(1);
    }
    console.log(`Bundle up to date (${sources.length} files, ${hash}).`);
    process.exit(0);
}

await mkdir(distDir, { recursive: true });
await writeFile(bundlePath, bundle);
await writeFile(manifestPath, manifest);
console.log(`Wrote public/dist/userinterface.js (${sources.length} files, ${(bundle.length / 1024).toFixed(0)} KB, ${hash}).`);
